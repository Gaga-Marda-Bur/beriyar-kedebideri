"""Generate mobile/lib/features/editor/services/arabic_pdf_layout_data.dart from BeriyaArabicProto-Regular.ttf."""
from pathlib import Path
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT_PATH = ROOT / 'docs/qa_arabic_diacritics/fonts/BeriyaArabicProto-Regular.ttf'
OUT_DART = ROOT / 'mobile/lib/features/editor/services/arabic_pdf_layout_data.dart'

# Standard Arabic + Beriya candidate bases -> (isol, fina, init, medi) Presentation Forms-B codepoints
# None means that contextual form does not exist (non-left-joining / right-joining only).
ARABIC_FORMS = {
    0x0621: (0xFE80, None, None, None),          # HAMZA
    0x0622: (0xFE81, 0xFE82, None, None),        # ALEF WITH MADDA ABOVE
    0x0623: (0xFE83, 0xFE84, None, None),        # ALEF WITH HAMZA ABOVE
    0x0624: (0xFE85, 0xFE86, None, None),        # WAW WITH HAMZA ABOVE
    0x0625: (0xFE87, 0xFE88, None, None),        # ALEF WITH HAMZA BELOW
    0x0626: (0xFE89, 0xFE8A, 0xFE8B, 0xFE8C),    # YEH WITH HAMZA ABOVE
    0x0627: (0xFE8D, 0xFE8E, None, None),        # ALEF
    0x0628: (0xFE8F, 0xFE90, 0xFE91, 0xFE92),    # BEH
    0x0629: (0xFE93, 0xFE94, None, None),        # TEH MARBUTA
    0x062A: (0xFE95, 0xFE96, 0xFE97, 0xFE98),    # TEH
    0x062B: (0xFE99, 0xFE9A, 0xFE9B, 0xFE9C),    # THEH
    0x062C: (0xFE9D, 0xFE9E, 0xFE9F, 0xFEA0),    # JEEM
    0x062D: (0xFEA1, 0xFEA2, 0xFEA3, 0xFEA4),    # HAH
    0x062E: (0xFEA5, 0xFEA6, 0xFEA7, 0xFEA8),    # KHAH
    0x062F: (0xFEA9, 0xFEAA, None, None),        # DAL
    0x0630: (0xFEAB, 0xFEAC, None, None),        # THAL
    0x0631: (0xFEAD, 0xFEAE, None, None),        # REH
    0x0632: (0xFEAF, 0xFEB0, None, None),        # ZAIN
    0x0633: (0xFEB1, 0xFEB2, 0xFEB3, 0xFEB4),    # SEEN
    0x0634: (0xFEB5, 0xFEB6, 0xFEB7, 0xFEB8),    # SHEEN
    0x0635: (0xFEB9, 0xFEBA, 0xFEBB, 0xFEBC),    # SAD
    0x0636: (0xFEBD, 0xFEBE, 0xFEBF, 0xFEC0),    # DAD
    0x0637: (0xFEC1, 0xFEC2, 0xFEC3, 0xFEC4),    # TAH
    0x0638: (0xFEC5, 0xFEC6, 0xFEC7, 0xFEC8),    # ZAH
    0x0639: (0xFEC9, 0xFECA, 0xFECB, 0xFECC),    # AIN
    0x063A: (0xFECD, 0xFECE, 0xFECF, 0xFED0),    # GHAIN
    0x0641: (0xFED1, 0xFED2, 0xFED3, 0xFED4),    # FEH
    0x0642: (0xFED5, 0xFED6, 0xFED7, 0xFED8),    # QAF
    0x0643: (0xFED9, 0xFEDA, 0xFEDB, 0xFEDC),    # KAF
    0x0644: (0xFEDD, 0xFEDE, 0xFEDF, 0xFEE0),    # LAM
    0x0645: (0xFEE1, 0xFEE2, 0xFEE3, 0xFEE4),    # MEEM
    0x0646: (0xFEE5, 0xFEE6, 0xFEE7, 0xFEE8),    # NOON
    0x0647: (0xFEE9, 0xFEEA, 0xFEEB, 0xFEEC),    # HEH
    0x0648: (0xFEED, 0xFEEE, None, None),        # WAW
    0x0649: (0xFEEF, 0xFEF0, None, None),        # ALEF MAKSURA
    0x064A: (0xFEF1, 0xFEF2, 0xFEF3, 0xFEF4),    # YEH
    0x06C6: (0xFBD9, 0xFBDA, None, None),        # OE
    0x06C7: (0xFBD7, 0xFBD8, None, None),        # U
    0x06CC: (0xFBFC, 0xFBFD, 0xFBFE, 0xFBFF),    # FARSI YEH
}

MARKS = {
    0x0300: 'bk_gravecomb',
    0x0301: 'bk_acutecomb',
    0x0304: 'bk_macroncomb',
    0x0307: 'bk_dotabovecomb',
}

f = TTFont(FONT_PATH)
upem = f['head'].unitsPerEm
ascent = f['hhea'].ascent
descent = f['hhea'].descent
cmap = f.getBestCmap()
hmtx = f['hmtx']
st = f['GPOS'].table.LookupList.Lookup[3].SubTable[0]

mark_anc = {}
for mcp, mg in MARKS.items():
    idx = st.MarkCoverage.glyphs.index(mg)
    a = st.MarkArray.MarkRecord[idx].MarkAnchor
    mark_anc[mcp] = (a.XCoordinate, a.YCoordinate)

pres_to_nominal = {}
forms_lines = []
anchors_lines = []

for nominal_cp, (isol, fina, init, medi) in sorted(ARABIC_FORMS.items()):
    # For isolated, prefer nominal_cp if present in cmap, else isol
    draw_isol = nominal_cp if nominal_cp in cmap else isol
    for p_cp in (isol, fina, init, medi):
        if p_cp is not None and p_cp in cmap:
            pres_to_nominal[p_cp] = nominal_cp

    def fmt(v):
        return 'null' if v is None else f'0x{v:04X}'

    forms_lines.append(
        f'  0x{nominal_cp:04X}: [{fmt(draw_isol)}, {fmt(fina)}, {fmt(init)}, {fmt(medi)}],'
    )

    for form_idx, draw_cp in enumerate((draw_isol, fina, init, medi)):
        if draw_cp is None or draw_cp not in cmap:
            continue
        gname = cmap[draw_cp]
        if gname not in st.BaseCoverage.glyphs:
            continue
        b_idx = st.BaseCoverage.glyphs.index(gname)
        ba = st.BaseArray.BaseRecord[b_idx].BaseAnchor[0]
        if ba is None:
            continue
        adv = hmtx[gname][0]
        for mcp, (mx, my) in sorted(mark_anc.items()):
            dx = ba.XCoordinate - mx
            dy = ba.YCoordinate - my
            key = f'{nominal_cp:04X}:{form_idx}:{mcp:04X}'
            anchors_lines.append(f"  '{key}': [{draw_cp}, {adv}, {dx}, {dy}],")

pres_lines = [f'  0x{p:04X}: 0x{n:04X},' for p, n in sorted(pres_to_nominal.items())]

dart_src = f'''// GENERATED BY docs/qa_arabic_diacritics/generate_arabic_pdf_layout_dart.py
// Source font: BeriyaArabicProto-Regular.ttf (SIL OFL 1.1)
// Do not edit manually.

const int arabicPdfUnitsPerEm = {upem};
const int arabicPdfAscent = {ascent};
const int arabicPdfDescent = {descent};

/// Contextual Presentation Forms-B codepoints: [isol, fina, init, medi].
const Map<int, List<int?>> arabicContextualForms = {{
{chr(10).join(forms_lines)}
}};

/// Reverse mapping from Presentation Forms-B back to nominal Unicode U+06xx
/// for /ToUnicode CMap preservation.
const Map<int, int> arabicPresentationToNominal = {{
{chr(10).join(pres_lines)}
}};

/// GPOS Lookup 3 Class 0 anchors keyed by "<nominalHex>:<formIdx>:<markHex>":
/// [drawBaseCp, xAdvance, dx, dy].
const Map<String, List<int>> arabicGposAnchors = {{
{chr(10).join(anchors_lines)}
}};
'''

OUT_DART.write_text(dart_src, encoding='utf-8')
print(f'Wrote {OUT_DART} ({len(forms_lines)} letters, {len(anchors_lines)} anchor entries)')
